/**
 * Copies Leaflet (the map library the web app uses) into the app as text,
 * so the office map runs without fetching any script from the internet.
 * Run after changing the leaflet version: node scripts/build-leaflet.js
 */
const fs = require('fs');
const path = require('path');

const dist = path.join(__dirname, '..', 'node_modules', 'leaflet', 'dist');
const { version } = require('leaflet/package.json');
const js = fs.readFileSync(path.join(dist, 'leaflet.js'), 'utf8');
const css = fs.readFileSync(path.join(dist, 'leaflet.css'), 'utf8');

const out = `// Generated by scripts/build-leaflet.js from leaflet@${version}. Do not edit.
// Leaflet is BSD-2-Clause licensed: https://github.com/Leaflet/Leaflet/blob/main/LICENSE
export const LEAFLET_VERSION = ${JSON.stringify(version)};
export const LEAFLET_JS = ${JSON.stringify(js)};
export const LEAFLET_CSS = ${JSON.stringify(css)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'features', 'map', 'leaflet-bundle.ts'), out);
console.log(`leaflet ${version}: ${Math.round(out.length / 1024)} KB`);
